async page => {
  const log=[];
  const errors=[];
  const pending=[];
  page.on('response',r=>{if(r.url().includes('/api/'))pending.push(r.text().then(body=>log.push({method:r.request().method(),path:new URL(r.url()).pathname,status:r.status(),request:r.request().postData(),body})));});
  page.on('pageerror',e=>errors.push(e.message));
  const states=[];
  const state=async label=>states.push({label,text:await page.locator('main').innerText(),focus:await page.evaluate(()=>document.activeElement.id)});
  await page.setViewportSize({width:1280,height:800});
  await state('Initial Alice');
  await page.getByRole('button',{name:'Edit quantity'}).click();
  await page.getByRole('spinbutton',{name:'Quantity',exact:true}).fill('3');
  await state('Provisional quantity 3');
  await page.getByRole('button',{name:'Save',exact:true}).click();
  await page.getByRole('status').filter({hasText:'Cart updated'}).waitFor();
  await state('Saved 3');
  await page.getByRole('button',{name:'Edit quantity'}).click();
  await page.getByRole('spinbutton',{name:'Quantity',exact:true}).fill('4');
  const beforeCancel=log.length;
  await page.getByRole('button',{name:'Cancel',exact:true}).click();
  await state('Cancelled 4');
  await page.getByRole('button',{name:'Edit quantity'}).click();
  states.push({label:'Reopened after cancel',quantity:await page.getByRole('spinbutton',{name:'Quantity',exact:true}).inputValue(),networkBeforeCancel:beforeCancel,networkAfterCancel:log.length});
  await page.screenshot({path:'evidence/desktop-reopened.png'});
  await page.getByRole('button',{name:'Cancel',exact:true}).click();
  await page.reload();
  await page.getByText('Quantity: 3 · Total: 36',{exact:true}).waitFor();
  await state('Reload verifies persisted 3');
  await page.getByRole('combobox',{name:'Demo account'}).selectOption('bob');
  await page.getByText('Quantity: 2 · Total: 24',{exact:true}).waitFor();
  await state('Bob unchanged');
  await page.setViewportSize({width:360,height:740});
  await page.getByRole('button',{name:'Edit quantity'}).click();
  await page.getByRole('spinbutton',{name:'Quantity',exact:true}).fill('6');
  await page.getByRole('spinbutton',{name:'Quantity',exact:true}).press('Tab');
  await page.keyboard.press('Enter');
  states.push({label:'Narrow keyboard invalid 6',validation:await page.getByRole('spinbutton',{name:'Quantity',exact:true}).evaluate(e=>({valid:e.validity.valid,message:e.validationMessage})),scrollWidth:await page.evaluate(()=>document.documentElement.scrollWidth)});
  await page.screenshot({path:'evidence/narrow-invalid.png'});
  await page.getByRole('spinbutton',{name:'Quantity',exact:true}).fill('5');
  await page.getByRole('spinbutton',{name:'Quantity',exact:true}).press('Tab');
  await page.keyboard.press('Enter');
  await page.getByRole('status').filter({hasText:'Cart updated'}).waitFor();
  await state('Bob keyboard saved stock boundary 5');
  await page.screenshot({path:'evidence/narrow-saved.png'});
  await Promise.all(pending);
  console.log(JSON.stringify({browser:page.context().browser().version(),states,log,errors},null,2));
}
