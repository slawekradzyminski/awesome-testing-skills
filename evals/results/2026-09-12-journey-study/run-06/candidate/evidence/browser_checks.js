async page => {
 const out=[];
 const state=()=>page.evaluate(()=>({order:document.querySelector('#order').value,heading:document.querySelector('#heading').textContent,note:document.querySelector('#note').value,service:document.querySelector('#service').textContent,feedback:document.querySelector('#feedback').textContent,loading:document.querySelector('#loading').textContent}));
 await page.waitForFunction(()=>!document.querySelector('#save').disabled);
 out.push({check:'initial',state:await state()});
 await page.selectOption('#order','A200');
 await page.waitForFunction(()=>document.querySelector('#heading').textContent==='Order A200');
 await page.selectOption('#order','A100');
 await page.selectOption('#order','A200');
 await page.waitForTimeout(850);
 out.push({check:'out-of-order lookup',state:await state()});
 await page.fill('#note','LOCKER: 12');
 await page.click('#save');
 await page.waitForFunction(()=>document.querySelector('#feedback').textContent.includes('unavailable'));
 out.push({check:'rejection retains draft',state:await state()});
 await page.screenshot({path:'evidence/rejected-note.png'});
 await page.fill('#note','Assessment delivery instruction');
 await page.click('#save');
 await page.waitForFunction(()=>document.querySelector('#feedback').textContent.includes('saved'));
 await page.reload();
 await page.selectOption('#order','A200');
 await page.waitForFunction(()=>!document.querySelector('#save').disabled);
 out.push({check:'note persisted after reload',state:await state()});
 await page.fill('#note','Ring twice'); await page.click('#save');
 await page.waitForFunction(()=>!document.querySelector('#save').disabled);
 await page.locator('#save').focus();
 await page.keyboard.press('Tab');
 out.push({check:'keyboard express focus',state:await page.evaluate(()=>({id:document.activeElement.id,outline:getComputedStyle(document.activeElement).outline}))});
 await page.keyboard.press('Enter');
 await page.waitForFunction(()=>document.querySelector('#service').textContent==='express');
 await page.keyboard.press('Tab');
 out.push({check:'keyboard standard focus',state:await page.evaluate(()=>({id:document.activeElement.id,outline:getComputedStyle(document.activeElement).outline}))});
 await page.keyboard.press('Enter');
 await page.waitForFunction(()=>document.querySelector('#service').textContent==='standard');
 await page.setViewportSize({width:320,height:700});
 out.push({check:'narrow layout',state:await page.evaluate(()=>({width:innerWidth,scrollWidth:document.documentElement.scrollWidth}))});
 await page.screenshot({path:'evidence/narrow.png',fullPage:true});
 return out;
}
